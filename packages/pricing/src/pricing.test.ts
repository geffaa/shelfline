import { describe, expect, it } from "vitest";
import fc from "fast-check";
import vectors from "../vectors/vectors.json";
import { priceCart, refundAmount, resolveTaxRule, type LineInput } from "./index";

interface V { name: string; input: { lines: { unitPriceMinor: number; qty: number; discountMinor: number; rateBp: number; inclusive: boolean }[]; cashRoundingStep: number | null }; expected: ReturnType<typeof priceCart> extends infer R ? { lines: { totalMinor: number; taxMinor: number }[]; subtotalMinor: number; discountMinor: number; taxMinor: number; totalMinor: number; cashRoundingMinor: number; payableMinor: number } : never }
const toInputs = (v: V): LineInput[] => v.input.lines.map((l) => ({ unitPriceMinor: l.unitPriceMinor, qty: l.qty, discountMinor: l.discountMinor, tax: { rateBp: l.rateBp, inclusive: l.inclusive } }));

describe("golden vectors (generated by an independent Python reference)", () => {
  it("has 200 cart vectors", () => { expect((vectors as V[]).length).toBe(200); });
  for (const v of vectors as unknown as V[]) {
    it(v.name, () => {
      const r = priceCart(toInputs(v), { cashRoundingStep: v.input.cashRoundingStep });
      expect(r.lines.map((l) => ({ totalMinor: l.totalMinor, taxMinor: l.taxMinor }))).toEqual(v.expected.lines);
      expect({ subtotalMinor: r.subtotalMinor, discountMinor: r.discountMinor, taxMinor: r.taxMinor, totalMinor: r.totalMinor, cashRoundingMinor: r.cashRoundingMinor, payableMinor: r.payableMinor })
        .toEqual({ subtotalMinor: v.expected.subtotalMinor, discountMinor: v.expected.discountMinor, taxMinor: v.expected.taxMinor, totalMinor: v.expected.totalMinor, cashRoundingMinor: v.expected.cashRoundingMinor, payableMinor: v.expected.payableMinor });
    });
  }
});

describe("invariants (property)", () => {
  const line = fc.record({ unitPriceMinor: fc.integer({ min: 0, max: 500_000 }), qty: fc.integer({ min: 1, max: 20 }), pct: fc.integer({ min: 0, max: 100 }), rateBp: fc.constantFrom(0, 500, 1000, 2000), inclusive: fc.boolean() });
  it("line taxes sum to the cart tax; totals add up; payable differs from total only by cash rounding", () => {
    fc.assert(fc.property(fc.array(line, { minLength: 1, maxLength: 8 }), fc.constantFrom(null, 5), (ls, step) => {
      const r = priceCart(ls.map((l) => ({ unitPriceMinor: l.unitPriceMinor, qty: l.qty, discountMinor: Math.floor((l.unitPriceMinor * l.qty * l.pct) / 100), tax: { rateBp: l.rateBp, inclusive: l.inclusive } })), { cashRoundingStep: step });
      expect(r.lines.reduce((a, l) => a + l.taxMinor, 0)).toBe(r.taxMinor);
      expect(r.lines.reduce((a, l) => a + l.totalMinor, 0)).toBe(r.totalMinor);
      r.lines.forEach((l) => { expect(l.exTaxMinor + l.taxMinor).toBe(l.totalMinor); expect(l.taxMinor).toBeGreaterThanOrEqual(0); });
      expect(r.payableMinor).toBe(r.totalMinor + r.cashRoundingMinor);
      expect(Math.abs(r.cashRoundingMinor)).toBeLessThanOrEqual(step ? Math.floor(step / 2) : 0);
    }), { numRuns: 5000 });
  });
  it("rejects invalid input", () => {
    const ok = { unitPriceMinor: 100, qty: 1, discountMinor: 0, tax: { rateBp: 1000, inclusive: true } };
    expect(() => priceCart([{ ...ok, qty: 0 }])).toThrow(); expect(() => priceCart([{ ...ok, discountMinor: 101 }])).toThrow();
    expect(() => priceCart([{ ...ok, unitPriceMinor: 1.5 }])).toThrow(); expect(() => priceCart([{ ...ok, tax: { rateBp: 20000, inclusive: true } }])).toThrow();
  });
});

describe("resolveTaxRule", () => {
  const rates = [
    { region: null, rateBp: 1000, taxInclusive: true, validFrom: "2000-07-01", validTo: null },
    { region: "AU-WA", rateBp: 1200, taxInclusive: true, validFrom: "2026-01-01", validTo: "2027-01-01" },
  ];
  it("region-specific rate wins inside its range; default otherwise; ranges are [from, to)", () => {
    expect(resolveTaxRule(rates, "AU-WA", "2026-06-01")).toEqual({ rateBp: 1200, inclusive: true });
    expect(resolveTaxRule(rates, "AU-WA", "2027-01-01")).toEqual({ rateBp: 1000, inclusive: true });
    expect(resolveTaxRule(rates, "AU-VIC", "2026-06-01")).toEqual({ rateBp: 1000, inclusive: true });
    expect(resolveTaxRule(rates, null, "1999-01-01")).toBeNull();
  });
});

describe("refundAmount", () => {
  const base = { qty: 3, refundedQty: 0, totalMinor: 10000, refundedMinor: 0, taxMinor: 909, refundedTaxMinor: 0 };
  it("last units take the remainder: refunding in any steps returns exactly the total and the tax", () => {
    fc.assert(fc.property(fc.integer({ min: 1, max: 20 }), fc.integer({ min: 1, max: 5_000_000 }), fc.integer({ min: 0, max: 100 }), fc.array(fc.integer({ min: 1, max: 20 }), { minLength: 1, maxLength: 12 }), (qty, total, taxPct, steps) => {
      const tax = Math.floor((total * taxPct) / 1100);
      let line = { qty, refundedQty: 0, totalMinor: total, refundedMinor: 0, taxMinor: tax, refundedTaxMinor: 0 };
      let paid = 0, taxPaid = 0;
      for (const st of steps) {
        const want = Math.min(st, qty - line.refundedQty); if (want <= 0) break;
        const r = refundAmount(line, want);
        expect(r.amountMinor).toBeGreaterThanOrEqual(0); expect(r.taxMinor).toBeLessThanOrEqual(r.amountMinor);
        paid += r.amountMinor; taxPaid += r.taxMinor; line = { ...line, refundedQty: line.refundedQty + want, refundedMinor: paid, refundedTaxMinor: taxPaid };
      }
      if (line.refundedQty < qty) { const r = refundAmount(line, qty - line.refundedQty); paid += r.amountMinor; taxPaid += r.taxMinor; }
      expect(paid).toBe(total); expect(taxPaid).toBe(tax);
    }), { numRuns: 3000 });
  });
  it("golden: one of three units, then the other two", () => {
    expect(refundAmount(base, 1)).toEqual({ amountMinor: 3333, taxMinor: 303 });
    expect(refundAmount({ ...base, refundedQty: 1, refundedMinor: 3333, refundedTaxMinor: 303 }, 2)).toEqual({ amountMinor: 6667, taxMinor: 606 });
  });
  it("over-refund is capped to what remains; a fully refunded line returns nothing; bad qty throws", () => {
    expect(refundAmount({ ...base, refundedQty: 2, refundedMinor: 6667, refundedTaxMinor: 606 }, 5)).toEqual({ amountMinor: 3333, taxMinor: 303 });
    expect(refundAmount({ ...base, refundedQty: 3, refundedMinor: 10000, refundedTaxMinor: 909 }, 1)).toEqual({ amountMinor: 0, taxMinor: 0 });
    expect(() => refundAmount(base, 0)).toThrow();
  });
});

import rules from "../vectors/rules.json";
import { applyPromotions, resolvePrice } from "./rules";
describe("pricing v2 golden vectors (independent Python reference)", () => {
  const all = rules as unknown as { kind: "price" | "promo"; name: string; input: any; expected: any }[];
  it("has 240 vectors, 440 with the cart vectors", () => { expect(all.length).toBe(240); expect(all.length + (vectors as unknown[]).length).toBe(440); });
  it("they exercise ties, windows and stacking", () => {
    expect(all.filter((v) => v.kind === "price" && v.expected.priceBookId).length).toBeGreaterThan(30); expect(all.filter((v) => v.kind === "price" && !v.expected.priceBookId).length).toBeGreaterThan(10);
    expect(all.filter((v) => v.kind === "promo" && v.expected.some((e: any) => e.promotionIds.length > 1)).length).toBeGreaterThan(5); expect(all.filter((v) => v.kind === "promo" && v.expected.some((e: any) => e.discountMinor > 0)).length).toBeGreaterThan(40);
  });
  for (const v of all) it(v.name, () => {
    if (v.kind === "price") expect(resolvePrice(v.input.variantId, v.input.basePriceMinor, v.input.onDate, v.input.books)).toEqual(v.expected);
    else expect(applyPromotions(v.input.lines, v.input.promos, v.input.onDate)).toEqual(v.expected);
  });
});

describe("pricing v2 rules", () => {
  const b = (id: string, priority: number, prices: Record<string, number>, validFrom: string | null = null, validTo: string | null = null) => ({ id, priority, validFrom, validTo, prices });
  it("the higher priority book wins, a book out of date or without the variant is ignored, a tie goes to the smaller id", () => {
    const books = [b("b2", 10, { v: 900 }), b("b1", 50, { v: 800 }, "2026-12-01", "2026-12-31"), b("b0", 50, { w: 1 }), b("b3", 10, { v: 700 })];
    expect(resolvePrice("v", 1000, "2026-12-15", books)).toEqual({ unitPriceMinor: 800, priceBookId: "b1" });
    expect(resolvePrice("v", 1000, "2026-11-30", books)).toEqual({ unitPriceMinor: 900, priceBookId: "b2" }); expect(resolvePrice("v", 1000, "2027-01-01", books)).toEqual({ unitPriceMinor: 900, priceBookId: "b2" });
    expect(resolvePrice("x", 1000, "2026-12-15", books)).toEqual({ unitPriceMinor: 1000, priceBookId: null }); expect(resolvePrice("v", 1000, "2026-12-01", books).priceBookId).toBe("b1"); expect(resolvePrice("v", 1000, "2026-12-31", books).priceBookId).toBe("b1");
  });
  it("percent and per-unit promotions: the best single one, plus every stackable one, never more than the line", () => {
    const p = (id: string, o: object) => ({ id, kind: "percent" as const, valueBp: 1000, amountMinor: 0, variantIds: null, minQty: 1, validFrom: null, validTo: null, stackable: false, ...o });
    const lines = [{ variantId: "v", unitPriceMinor: 5000, qty: 2 }];
    expect(applyPromotions(lines, [p("a", {}), p("b", { valueBp: 2500 }), p("c", { kind: "amount_off", valueBp: 0, amountMinor: 1000 })], "2026-11-04")).toEqual([{ discountMinor: 2500, promotionIds: ["b"] }]);   // 25% beats 10% and 2 x 10.00
    expect(applyPromotions(lines, [p("a", { valueBp: 2000 }), p("s", { valueBp: 500, stackable: true })], "2026-11-04")).toEqual([{ discountMinor: 2500, promotionIds: ["a", "s"] }]);
    expect(applyPromotions(lines, [p("a", { valueBp: 9000 }), p("s", { valueBp: 5000, stackable: true })], "2026-11-04")[0]!.discountMinor).toBe(10000);
    expect(applyPromotions(lines, [p("m", { minQty: 3 }), p("o", { variantIds: ["z"] }), p("d", { validTo: "2026-11-03" })], "2026-11-04")).toEqual([{ discountMinor: 0, promotionIds: [] }]);
  });
});
